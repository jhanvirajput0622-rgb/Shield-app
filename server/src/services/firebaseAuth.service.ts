import { getApps, initializeApp } from "firebase-admin/app";
import { getAuth } from "firebase-admin/auth";

import { ApiError } from "../utils/ApiError";

/**
 * Bridges the API's identity (a custom JWT whose `sub` is the Firestore document
 * ID of the user) to Firebase Auth, so the mobile client can obtain a real
 * Firebase ID token.
 *
 * ── Why this exists ──────────────────────────────────────────────────────────
 * The client-owned schema in artifacts/mobile/lib/firestore/ is authorised by
 * `firestore.rules` on `request.auth.uid`. The API's own JWT cannot drive that:
 * Firestore only ever sees a Firebase ID token. So the client trades its API
 * access token for a Firebase custom token here, signs in with it, and from then
 * on `auth.uid` is the same value the API calls `req.userId`.
 *
 * That equality is the whole point. `lib/firestore/schema.ts` documents the ERD's
 * `user_id` primary key as *being* the document ID and *being* `auth.uid`; the
 * ownership rules in every block are `request.auth.uid == userId`. Minting the
 * token with the server's user ID as the Firebase uid is what makes those rules
 * work without a second identity space.
 *
 * ── Why get-or-create ─────────────────────────────────────────────────────────
 * `createCustomToken` will happily sign a token for a uid that does not exist,
 * but `signInWithCustomToken` on the client then fails with
 * `auth/user-not-found`. So the Firebase user must exist first. Registration and
 * every other signup path live in userService, and none of them know about
 * Firebase, so the user is created lazily here on first request instead.
 *
 * ── Availability ──────────────────────────────────────────────────────────────
 * This needs the Admin SDK's Auth surface, which requires real credentials and a
 * project with Firebase Auth enabled. Neither exists in the test/CI environment
 * (the emulator provides Firestore only), so every failure mode funnels into
 * `FirebaseAuthUnavailableError` and the controller answers 501. The app treats
 * 501 as "Firestore direct access is off" and falls back to the API — see
 * artifacts/mobile/lib/firebaseAuth.ts.
 */

/** Thrown when Firebase Auth cannot be reached. Surfaces as HTTP 501. */
export class FirebaseAuthUnavailableError extends Error {
  readonly cause?: unknown;

  constructor(message: string, cause?: unknown) {
    super(message);
    this.name = "FirebaseAuthUnavailableError";
    this.cause = cause;
  }
}

/**
 * The Firebase uid charset. Firebase accepts `[A-Za-z0-9-]{1,128}`.
 *
 * The server's user IDs come from `randomUUID()`, which is hex plus dashes and
 * therefore always valid — but this is checked rather than assumed, because a
 * uid that Firebase silently mangles would desynchronise it from the server's
 * user ID and quietly break every ownership rule. Failing loudly is the point.
 */
const FIREBASE_UID_PATTERN = /^[A-Za-z0-9-]{1,128}$/;

function assertUsableUid(userId: string): void {
  if (!FIREBASE_UID_PATTERN.test(userId)) {
    throw new Error(
      `User id ${JSON.stringify(userId)} cannot be used as a Firebase uid. ` +
        "The client-owned Firestore schema keys ownership on auth.uid, so the " +
        "two ids have to be the same value. User ids are generated by " +
        "userService as UUIDs; a non-conforming one means that changed."
    );
  }
}

/**
 * The Admin SDK's `getAuth()` needs an initialised app. `initFirestore()` already
 * initialises one for Firestore, so reuse it rather than creating a second app —
 * Firebase throws on a duplicate default app.
 */
function ensureApp(): void {
  if (getApps().length === 0) {
    const projectId =
      process.env.FIREBASE_PROJECT_ID ??
      process.env.GOOGLE_CLOUD_PROJECT ??
      (process.env.FIRESTORE_EMULATOR_HOST ? "demo-shield" : undefined);

    initializeApp({ projectId });
  }
}

/**
 * True when this process can plausibly mint custom tokens.
 *
 * The Firestore emulator serves Firestore but not Auth, so any emulator host
 * means the feature is off. This is only a fast pre-check for logging and for a
 * clearer error; the real gate is the try/catch in `issueCustomToken`.
 */
export function isFirebaseAuthConfigured(): boolean {
  if (process.env.FIRESTORE_EMULATOR_HOST) return false;
  return Boolean(
    process.env.FIREBASE_PROJECT_ID ||
      process.env.GOOGLE_APPLICATION_CREDENTIALS ||
      process.env.GOOGLE_CLOUD_PROJECT
  );
}

export interface FirebaseSessionGrant {
  /** Custom token to pass to `signInWithCustomToken` on the client. */
  token: string;
  /** The Firebase uid, equal to the server's user id. */
  uid: string;
}

/**
 * Mint a Firebase custom token for an already-authenticated API user.
 *
 * @param userId `req.userId` — the Firestore document ID of the user.
 * @param email  Used to populate the Firebase profile when the account is first
 *               created. Never load-bearing: identity comes from the uid, and
 *               the fallback path below creates the user without it.
 *
 * @throws {FirebaseAuthUnavailableError} when Firebase Auth is unreachable.
 * @throws {Error} when `userId` is not a legal Firebase uid.
 */
export async function issueCustomToken(
  userId: string,
  email?: string
): Promise<FirebaseSessionGrant> {
  assertUsableUid(userId);
  ensureApp();

  try {
    const auth = getAuth();

    // Create the Firebase user on first use. `getUser` rejecting with
    // `auth/user-not-found` is the normal path for every brand-new account, so
    // it is handled rather than treated as an error.
    try {
      await auth.getUser(userId);
    } catch (error) {
      const code = (error as { code?: string }).code;
      if (code !== "auth/user-not-found") throw error;

      try {
        await auth.createUser({
          uid: userId,
          ...(email ? { email } : {}),
          // The API already proved control of this address by verifying the
          // password or a Google ID token, so Firebase should not re-send a
          // verification email for it.
          emailVerified: Boolean(email),
        });
      } catch (createError) {
        const createCode = (createError as { code?: string }).code;

        // The address is already registered in Firebase under a different uid —
        // e.g. the same person has two Shield accounts. Re-creating with the
        // email would fail, and the uid is the only thing that actually matters
        // here, so create the user without one rather than failing the request.
        if (createCode === "auth/email-already-exists") {
          await auth.createUser({ uid: userId });
        } else {
          throw createError;
        }
      }
    }

    const token = await auth.createCustomToken(userId);
    return { token, uid: userId };
  } catch (error) {
    if (error instanceof FirebaseAuthUnavailableError) throw error;

    const code = (error as { code?: string }).code;
    throw new FirebaseAuthUnavailableError(
      code === "auth/operation-not-allowed" || code === "auth/admin-restricted-operation"
        ? "Firebase Auth is not enabled for this project, or the service account cannot use it. " +
          "Enable the Identity Platform API and grant the service account the Firebase Authentication " +
          "Administrator role."
        : `Firebase Auth is unavailable, so the client cannot obtain an ID token (${code ?? "unknown error"}). ` +
          "The app falls back to the REST API when this is unavailable.",
      error
    );
  }
}

/**
 * Map the service error onto an HTTP error for the controller.
 *
 * `FirebaseAuthUnavailableError` is 501 rather than 500 on purpose: nothing is
 * broken, a capability is switched off, and the client branches on the status to
 * decide whether to fall back to the API. A genuine 500 would read as "retry",
 * which would never succeed.
 */
export function toApiError(error: unknown): ApiError {
  if (error instanceof FirebaseAuthUnavailableError) {
    return ApiError.notImplemented(error.message);
  }
  return ApiError.internal("Internal server error");
}
